// English snapshot taken from the DOM on load
const EN = {};

// ================= State =================
let currentLang = "en";
let currentTheme = "dark";

// Remember the visitor's choices when storage is available (fails silently otherwise)
function load(key) { try { return localStorage.getItem(key); } catch { return null; } }
function save(key, value) { try { localStorage.setItem(key, value); } catch { /* ignore */ } }

const htmlEl = document.documentElement;
const langToggle = document.getElementById("langToggle");
const themeToggle = document.getElementById("themeToggle");
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");
const iconSun = document.getElementById("iconSun");
const iconMoon = document.getElementById("iconMoon");

// Snapshot English strings
document.querySelectorAll("[data-i18n]").forEach((el) => {
  EN[el.dataset.i18n] = el.innerHTML;
});

// ================= Language toggle =================
function applyLang(lang) {
  currentLang = lang;
  const dict = lang === "ar" ? AR : EN;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  htmlEl.lang = lang;
  htmlEl.dir = lang === "ar" ? "rtl" : "ltr";
  langToggle.textContent = lang === "ar" ? "EN" : "عربي";
  langToggle.setAttribute("aria-label", lang === "ar" ? "Switch to English" : "التبديل إلى العربية");
  document.title = lang === "ar"
    ? "رياض بيتموني — مهندس برمجيات · الذكاء الاصطناعي وتطبيقات الهواتف"
    : "Riad Baytamouni — Software Engineer · AI & Mobile Apps | UAE";
  save("lang", lang);
}

langToggle.addEventListener("click", () => {
  applyLang(currentLang === "en" ? "ar" : "en");
});
if (load("lang") === "ar") applyLang("ar");

// ================= Theme toggle (saved choice, then system preference, then dark) =================
function applyTheme(theme) {
  currentTheme = theme;
  htmlEl.dataset.theme = theme;
  iconSun.hidden = theme === "light";
  iconMoon.hidden = theme === "dark";
}
const savedTheme = load("theme");
applyTheme(
  savedTheme === "light" || savedTheme === "dark"
    ? savedTheme
    : window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark"
);

themeToggle.addEventListener("click", () => {
  applyTheme(currentTheme === "dark" ? "light" : "dark");
  save("theme", currentTheme);
});

// ================= Mobile menu =================
menuToggle.addEventListener("click", () => {
  const open = navLinks.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(open));
});
navLinks.addEventListener("click", (e) => {
  if (e.target.tagName === "A") {
    navLinks.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  }
});

// ================= Scroll reveal =================
const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12, rootMargin: "0px 0px -40px 0px" }
);
document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));

